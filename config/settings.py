    # Public URL base of the bucket (the bucket must be set to PUBLIC in Supabase):
    # https://<ref>.storage.supabase.co/storage/v1/object/public/<bucket>
    SUPABASE_PUBLIC_BASE = (
        SUPABASE_S3_ENDPOINT.rstrip("/").replace("/storage/v1/s3", "/storage/v1/object/public")
        + f"/{SUPABASE_S3_BUCKET_NAME}"
    )

    MEDIA_URL = SUPABASE_PUBLIC_BASE + "/"

    default_storage = {
        "BACKEND": "storages.backends.s3.S3Storage",
        "OPTIONS": {
            "access_key": SUPABASE_S3_ACCESS_KEY,
            "secret_key": SUPABASE_S3_SECRET_KEY,
            "bucket_name": SUPABASE_S3_BUCKET_NAME,
            "endpoint_url": SUPABASE_S3_ENDPOINT,
            "region_name": SUPABASE_S3_REGION,

            "addressing_style": "path",
            "signature_version": "s3v4",
            "default_acl": None,
            "querystring_auth": False,
            "file_overwrite": False,

            # FIX: without this, logo.url points to the private S3 endpoint
            # (not a public URL), so images don't show. custom_domain makes
            # logo.url = https://<ref>.storage.supabase.co/storage/v1/object/public/<bucket>/<file>
            "custom_domain": SUPABASE_PUBLIC_BASE.replace("https://", "", 1),
            "url_protocol": "https:",
        },
    }
